# Исходная необработанная строка из источника данных
raw_user_record = " 10827 ; aLeXanDer_vLaDimiRov ; mInSk ; ACTIVE "

# Шаг 1. Разбиваем сырую строку на части по разделителю ";".
# Метод .split() возвращает список строк: идентификатор, имя, город, статус.
parts = raw_user_record.split(";")

# Шаг 2. У каждого элемента убираем пробелы в начале и в конце через .strip().
# Методы строк не меняют исходную строку — они возвращают новую очищенную копию.
user_id = parts[0].strip()
name = parts[1].strip()
city = parts[2].strip()
status = parts[3].strip()

# Шаг 3. К идентификатору добавляем префикс UID- с помощью f-строки.
user_id = f"UID-{user_id}"

# Шаг 4. В имени меняем нижнее подчёркивание на пробел (.replace),
# затем каждое слово делаем с заглавной буквы (.title).
name = name.replace("_", " ").title()

# Шаг 5. Название города приводим к верхнему регистру.
city = city.upper()

# Шаг 6. Статус пользователя приводим к нижнему регистру.
status = status.lower()

# Шаг 7. Собираем обработанные поля в одну строку с разделителем " | ".
normalized_record = " | ".join([user_id, name, city, status])

print(f"Нормализованная запись: {normalized_record}")
